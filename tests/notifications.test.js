// Website notifications: the news the site e-mails about is also kept on the website, with e-mail off.
const crypto = require('node:crypto');
const { BASE, sql, ok, done, mkUsers, PNG } = require('./helpers/common.js');
const smtp = require('./helpers/fake-smtp.js');
const { launch, axeViolations } = require('./helpers/browser.js');
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));
const ip = () => '10.3.' + Math.floor(Math.random() * 250) + '.' + (Math.floor(Math.random() * 250) + 1);
const H = (t) => ({ 'Content-Type': 'application/json', cookie: 'token=' + t, 'x-forwarded-for': ip() });
const call = (method, path, t, body) => fetch(BASE + path, { method, headers: H(t), body: body === undefined ? undefined : JSON.stringify(body) });
const list = async (t, qs = '') => (await call('GET', '/api/notifications' + qs, t)).json();
