// The admin activity log: the key admin actions each leave one line saying who did what.
const crypto = require('node:crypto');
const { BASE, sql, ok, done, mkUsers, PNG } = require('./helpers/common.js');
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));
const H = (t) => ({ 'Content-Type': 'application/json', cookie: 'token=' + t, 'x-forwarded-for': '203.0.113.' + (Math.floor(Math.random() * 250) + 1) });
const call = (method, path, t, body) => fetch(BASE + path, { method, headers: H(t), body: body === undefined ? undefined : JSON.stringify(body) });
const key = () => 'k' + crypto.randomBytes(8).toString('hex');

(async () => {
  const u = await mkUsers('al');
  const other = await mkUsers('ao');
  const target = other.bId;
  const adminId = Number(sql(`SELECT id FROM users WHERE email='${u.m.a}'`));
  const mine = async (qs = '') => (await (await call('GET', '/api/admin/activity?admin=' + adminId + qs, u.aT)).json());
  const has = async (action, test = () => true) => { await sleep(150); const rows = (await mine('&action=' + action)).rows; return rows.find(test); };

  console.log('\n== people');
  await call('PATCH', `/api/admin/users/${target}`, u.aT, { status: 'suspended' });
  let row = await has('user_suspended', (r) => r.targetId === String(target));
  ok(row && row.adminName === 'al Admin' && row.targetType === 'user' && row.details === other.m.b && row.ip.startsWith('203.0.113.'), 'suspending is logged with who, whom, and the address', row);
  await call('PATCH', `/api/admin/users/${target}`, u.aT, { status: 'active' });
  ok(await has('user_reactivated'), 'reactivating is logged');
  await call('PATCH', `/api/admin/users/${target}`, u.aT, { role: 'partner' });
  row = await has('user_role_changed');
  ok(row && row.details === `${other.m.b}: buyer → partner`, 'a role change says from what to what', row);
  await call('PATCH', `/api/admin/users/${target}`, u.aT, { role: 'partner' });
  ok((await mine('&action=user_role_changed')).total === 1, 'saving the same role again logs nothing');
  const res = await call('POST', `/api/admin/users/${target}/reset-password`, u.aT);
  const pw = (await res.json()).password;
  row = await has('user_password_reset');
  ok(row && row.targetId === String(target) && !JSON.stringify(row).includes(pw), 'a password reset is logged without the new password', row);
  await call('PATCH', `/api/admin/users/${target}`, u.aT, { role: 'buyer' });
  await call('POST', '/api/admin/users/bulk', u.aT, { role: 'buyer', users: [{ name: 'Bulk One', email: `bulk1-${u.st}@test.invalid`, phone: '12345678' }] });
  row = await has('users_bulk_created');
  ok(row && /1 created as buyer/.test(row.details), 'adding users in a batch is logged with the numbers', row);

  console.log('\n== documents, points, registrations');
  await call('PUT', `/api/admin/buyer-profiles/${target}/documents/passportFront`, u.aT, { value: PNG });
  await call('PATCH', `/api/admin/buyer-profiles/${target}/documents/passportFront`, u.aT, { status: 'rejected', note: 'Too dark' });
  row = await has('document_rejected');
  ok(row && row.details === 'passportFront: Too dark' && row.targetId === String(target), 'a rejected document is logged with the reason', row);
  await call('PATCH', `/api/admin/buyer-profiles/${target}/documents/passportFront`, u.aT, { status: 'verified' });
  ok(await has('document_verified'), 'a verified document is logged');
  ok(await has('document_uploaded'), 'an upload by an admin is logged');
  await call('POST', '/api/admin/buyer-profiles/bulk-review', u.aT, { userIds: [target], action: 'verify' });
  row = await has('documents_bulk_verified');
  ok(row && /of 1 buyers/.test(row.details), 'bulk verify is logged', row);
  await call('POST', `/api/admin/wallet/wallets/${target}`, u.aT, { action: 'adjust', amount: 25, note: 'Welcome gift', key: key() });
  row = await has('points_adjusted');
  ok(row && row.details === '+25 points: Welcome gift', 'adding points is logged with the amount and reason', row);
  const k = key();
  await call('POST', `/api/admin/wallet/wallets/${target}`, u.aT, { action: 'adjust', amount: 5, note: 'Once', key: k });
  await call('POST', `/api/admin/wallet/wallets/${target}`, u.aT, { action: 'adjust', amount: 5, note: 'Once', key: k });
  await sleep(200);
  ok((await mine('&action=points_adjusted')).rows.filter((r) => r.details === '+5 points: Once').length === 1, 'a repeated (replayed) request is logged once');
  await call('POST', '/api/admin/wallet/bulk-adjust', u.aT, { userIds: [target], amount: 10, note: 'Thanks', key: key() });
  ok(await has('points_bulk_given', (r) => /10 points to 1 buyers: Thanks/.test(r.details)), 'bulk points are logged');
  await call('POST', `/api/admin/wallet/wallets/${target}`, u.aT, { action: 'freeze' });
  await call('POST', `/api/admin/wallet/wallets/${target}`, u.aT, { action: 'unfreeze' });
  ok((await has('wallet_frozen')) && (await has('wallet_unfrozen')), 'freezing and unfreezing are logged');
  await call('PUT', '/api/admin/wallet/settings', u.aT, { transferMax: 1000, transferDailyMax: 5000, withdrawMin: 100, transfersEnabled: true, withdrawalsEnabled: false, topupInstructions: 'x', companyAlipayQr: '', companyWechatQr: '', companyBankDetails: '' });
  ok(await has('wallet_settings_saved', (r) => /withdrawals off/.test(r.details)), 'wallet settings are logged');
  ok(!(await call('POST', `/api/admin/wallet/wallets/${target}`, u.bT, { action: 'freeze' })).ok, 'a buyer cannot do it');
  await sleep(200);
  ok((await mine('&action=wallet_frozen')).total === 1, 'and the refused try leaves no line');

  console.log('\n== content and settings');
  const slug = 'activity-' + u.st;
  let r = await call('POST', '/api/admin/exhibitions', u.aT, { title: 'Activity Expo', slug, startDate: '2030-01-01', endDate: '2030-01-03' });
  const exId = (await r.json()).id;
  ok(r.status === 201 && (await has('exhibition_created', (q) => q.targetId === String(exId) && q.details === 'Activity Expo')), 'creating an exhibition is logged with its title');
  r = await call('PUT', `/api/admin/exhibitions/${exId}`, u.aT, { title: 'Activity Expo 2', slug, startDate: '2030-01-01', endDate: '2030-01-03' });
  ok(r.status === 200 && (await has('exhibition_updated', (q) => q.targetId === String(exId))), 'editing is logged');
  r = await call('DELETE', `/api/admin/exhibitions/${exId}`, u.aT);
  ok(r.status === 200 && (await has('exhibition_deleted', (q) => q.targetId === String(exId))), 'deleting is logged');
  await call('PUT', '/api/admin/email', u.aT, { enabled: false, host: 'smtp.example.test', port: 587, secure: false, username: 'u', password: 'super-secret-smtp-password', fromName: 'The Unique Expo', fromEmail: '' });
  row = await has('mail_settings_saved');
  ok(row && /smtp\.example\.test/.test(row.details) && /password changed/.test(row.details) && !JSON.stringify(row).includes('super-secret'), 'e-mail settings are logged, the password never is', row);
  r = await call('POST', '/api/admin/email', u.aT, { action: 'reminderKey' });
  const rk = (await r.json()).key;
  ok(r.status === 200 && (await has('reminder_key_made')) && !JSON.stringify(await mine()).includes(rk), 'making a reminder key is logged, the key is not');
  sql("DELETE FROM mail_settings");

  console.log('\n== the log itself');
  const all = await mine();
  ok(all.total >= 20 && all.rows.length === 50 || all.rows.length === all.total, 'a page holds up to 50 lines, newest first', [all.total, all.rows.length]);
  ok(all.rows.every((q, i) => i === 0 || q.id < all.rows[i - 1].id), 'newest first');
  ok(all.actions.includes('points_adjusted') && all.admins.some((a) => a.id === adminId && a.name === 'al Admin'), 'the filter lists are filled');
  const s = await (await call('GET', '/api/admin/activity?q=' + encodeURIComponent('Welcome gift'), u.aT)).json();
  ok(s.total >= 1 && s.rows.every((q) => /Welcome gift/.test(q.details)), 'search finds by words in the details');
  const inj = await call('GET', '/api/admin/activity?q=' + encodeURIComponent("%' OR 1=1 -- ") + '&action=' + encodeURIComponent("x' OR '1'='1"), u.aT);
  ok(inj.status === 200 && (await inj.json()).total === 0, 'search text is never run as SQL');
  const wild = await (await call('GET', '/api/admin/activity?q=' + encodeURIComponent('%'), u.aT)).json();
  ok(wild.rows.every((q) => JSON.stringify(q).includes('%')), 'a % in the search is a plain character, not a wildcard', wild.total);
  const big = await (await call('GET', '/api/admin/activity?page=999999', u.aT)).json();
  ok(big.rows.length === 0, 'a page far past the end is empty, not an error');
  const bad = await call('GET', '/api/admin/activity?page=abc&admin=x', u.aT);
  ok(bad.status === 200, 'nonsense page numbers are tolerated');
  ok((await fetch(BASE + '/api/admin/activity')).status === 401, 'signed-out cannot read it');
  done();
})().catch((e) => { console.error(e); process.exit(1); });
