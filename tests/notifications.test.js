  let r = await call('PATCH', `/api/admin/expo-registrations/${regId}`, u.aT, { status: 'approved', confirmBy });
  ok(r.status === 200, 'an admin approves a registration');
  l = await waitFor(u.bT, 'registrationApproved');
  let n = l.items.find((x) => x.kind === 'registrationApproved');
  ok(n && n.params.expo === 'Notify Expo ' + st && n.params.date === confirmBy && n.path === '/dashboard/buyer/registrations' && n.read === false, 'the buyer is told, with the exhibition, the confirm-by date and where to go', n);
  r = await call('PATCH', `/api/admin/expo-registrations/${regId}`, u.aT, { status: 'rejected' });
  l = await waitFor(u.bT, 'registrationRejected');
  ok(l.items.some((x) => x.kind === 'registrationRejected' && x.params.expo === 'Notify Expo ' + st), 'a rejection is told too');
