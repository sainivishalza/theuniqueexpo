  ok(!JSON.stringify(l).includes(other.m.b), 'and nothing about anybody else');
  ok((await list(other.bT)).items.length === 0, 'another person has none of them');

  console.log('\n== reading');
  const first = l.items[0];
  r = await call('POST', '/api/notifications', myT, { action: 'read', id: first.id });
  j = await r.json(); ok(r.status === 200 && j.unread === 4, 'marking one as read lowers the count', j);
  r = await call('POST', '/api/notifications', myT, { action: 'read', id: first.id });
