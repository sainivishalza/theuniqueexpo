  console.log('\n== the news arrives (e-mail is off)');
  sql(`INSERT INTO exhibitions (slug,title,start_date,end_date) VALUES ('nt-expo-${st}','Notify Expo ${st}',DATE_ADD(UTC_DATE(),INTERVAL 30 DAY),DATE_ADD(UTC_DATE(),INTERVAL 33 DAY))`);
  const ex = Number(sql(`SELECT id FROM exhibitions WHERE slug='nt-expo-${st}'`));
  sql(`INSERT INTO expo_registrations (exhibition_id,user_id,status) VALUES (${ex},${bId},'pending')`);
  const regId = Number(sql(`SELECT id FROM expo_registrations WHERE user_id=${bId} AND exhibition_id=${ex}`));
