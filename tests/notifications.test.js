  r = await call('POST', '/api/notifications', other.bT, { action: 'read', id: l.items[1].id });
  ok(r.status === 404, 'nobody can mark someone else\'s as read');
  ok((await list(myT)).unread === 4, 'and it stayed unread');
  r = await call('POST', '/api/notifications', myT, { action: 'read', id: 'x' }); ok(r.status === 400, 'a bad id is refused');
  r = await call('POST', '/api/notifications', myT, { action: 'nonsense' }); ok(r.status === 400, 'an unknown action is refused');
  r = await call('POST', '/api/notifications', myT, { action: 'readAll' }); ok(r.status === 200 && (await r.json()).unread === 0, '"mark all as read"');
  ok((await list(myT)).unread === 0, 'the count is 0');
  ok((await list(other.bT)).unread === 0, 'and did not touch anyone else');

  console.log('\n== older ones and the clean-up');
  sql(`INSERT INTO user_notifications (user_id,kind,params,path) SELECT ${bId},'pointsReceived','{"points":"1","reason":"bulk"}','' FROM (SELECT 1 FROM information_schema.columns LIMIT 40) t`);
  l = await list(myT);
  ok(l.items.length === 30 && l.hasMore === true, 'a page holds 30 and says there are more', [l.items.length, l.hasMore]);
  const l2 = await list(myT, '?before=' + l.items[l.items.length - 1].id);
  ok(l2.items.length === 15 && l2.hasMore === false && l2.items[0].id < l.items[29].id, 'the next page continues where it stopped', [l2.items.length]);
  sql(`INSERT INTO user_notifications (user_id,kind,params,path,created_at) VALUES (${bId},'pointsReceived','{"points":"9","reason":"ancient"}','',DATE_SUB(NOW(), INTERVAL 200 DAY))`);
  const crypto2 = require('node:crypto'); sql(`DELETE FROM rate_limits WHERE key_hash='${crypto2.createHash('sha256').update('housekeeping-daily').digest('hex')}'`);
  await call('GET', '/api/admin/attention', u.aT).catch(() => null);
  await (await fetch(BASE + '/api/admin/attention', { headers: H(u.aT) })).text();
  for (let i = 0; i < 30 && sql(`SELECT COUNT(*) FROM user_notifications WHERE user_id=${bId} AND params LIKE '%ancient%'`) !== '0'; i++) await sleep(200);
  ok(sql(`SELECT COUNT(*) FROM user_notifications WHERE user_id=${bId} AND params LIKE '%ancient%'`) === '0', 'a notification older than 180 days is cleaned up');
  ok(sql(`SELECT COUNT(*) FROM user_notifications WHERE user_id=${bId}`) === '45', 'the newer ones stay');
  sql(`DELETE FROM user_notifications WHERE user_id=${bId} AND params LIKE '%bulk%'`);

  console.log('\n== tour registrations');
  sql(`INSERT INTO tours (slug,title,start_date,end_date,duration,departure_city,destination,description,highlights,price,currency,group_size,organizer,color,image,registration_form_schema) VALUES ('nt-tour-${st}','Notify Tour ${st}',DATE_ADD(UTC_DATE(),INTERVAL 40 DAY),DATE_ADD(UTC_DATE(),INTERVAL 45 DAY),'5 days','Guangzhou','Yiwu','d','[]',100,'USD','10','Org','#000','','[]')`);
  const tourId = Number(sql(`SELECT id FROM tours WHERE slug='nt-tour-${st}'`));
