  r = await call("PATCH", `/api/admin/buyer-profiles/${bId}/documents/passportFront`, u.aT, { status: 'rejected', note: 'Too dark to read' });
  l = await waitFor(u.bT, 'documentRejected');
  n = l.items.find((x) => x.kind === 'documentRejected');
  ok(n && n.params.reason === 'Too dark to read' && typeof n.params.document === 'string' && /passport/i.test(n.params.document), 'a document sent back names the document and the reason', n && n.params);
  l = await list(u.bT, '?locale=ru'); n = l.items.find((x) => x.kind === 'documentRejected');
  ok(n && n.params.document !== undefined && typeof n.params.document === 'string' && n.params.document.length > 0, 'the document name is given in the reader\'s language (or English when there is no translation)', n && n.params.document);
  r = await call('POST', `/api/admin/wallet/wallets/${bId}`, u.aT, { action: 'adjust', amount: 120, note: 'Welcome gift', key: 'k' + crypto.randomBytes(8).toString('hex') });
  l = await waitFor(u.bT, 'pointsReceived');
  n = l.items.find((x) => x.kind === 'pointsReceived');
  ok(n && n.params.points === '120' && n.params.reason === 'Welcome gift', 'points received: the amount and the reason', n && n.params);
  r = await call('POST', `/api/admin/wallet/wallets/${bId}`, u.aT, { action: 'adjust', amount: -20, note: 'Correction', key: 'k' + crypto.randomBytes(8).toString('hex') });
  await sleep(500);
  l = await list(u.bT);
  ok(l.items.filter((x) => x.kind === 'pointsReceived').length === 1, 'taking points away tells nothing (as with e-mail)');
